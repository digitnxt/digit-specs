class TestBR_CM_002_vault_encryption_fails_hard_when_enabled:
    """
    When VAULT_ENABLED=true, mobileNumber and email are encrypted/decrypted via Vault.
    This is an infrastructure-level rule — observable only when Vault is intentionally
    unavailable. We test the contract: create succeeds when service is running normally,
    and document the expected 500 when Vault is unreachable.
    """

    def test_create_succeeds_when_vault_operational(self, request, base_url, auth_headers):
        mobile = _build_mobile()
        resp = _post(request.node, f"{base_url}/individuals", auth_headers,
                     {"individual": {"givenName": "VaultTest", "mobileNumber": mobile}})
        assert resp.status_code in (200, 201), \
            "Individual create must succeed when Vault is operational (or VAULT_ENABLED=false)"


def _build_mobile():
    import uuid
    return f"+91{uuid.uuid4().int % 10_000_000_000:010d}"


class TestBR_CM_003_pubsub_events_are_fire_and_forget:
    """Create succeeds regardless of PubSub availability."""

    def test_create_returns_success_independent_of_pubsub(
        self, request, base_url, auth_headers
    ):
        import uuid
        mobile = f"+91{uuid.uuid4().int % 10_000_000_000:010d}"
        resp = _post(request.node, f"{base_url}/individuals", auth_headers,
                     {"individual": {"givenName": "PubSubTest", "mobileNumber": mobile}})
        assert resp.status_code in (200, 201), \
            f"Create must succeed regardless of PubSub availability, got {resp.status_code}: {resp.text}"
