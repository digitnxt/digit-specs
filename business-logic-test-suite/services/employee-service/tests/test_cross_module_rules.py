"""
Cross-module rule tests for Employee service.
All tests skip when the required dep URL is absent.
"""
import uuid
import pytest
import requests as req_lib
from tests.helpers.curl_builder import attach_curl


def _post(node, url, headers, body):
    r = req_lib.Request("POST", url, headers=headers, json=body)
    p = r.prepare()
    attach_curl(node, p)
    return req_lib.Session().send(p)


def _base_employee():
    return {
        "employeeType": "PERMANENT",
        "department": "IT",
        "designation": "Engineer",
        "jurisdictions": [{
            "boundaryRelation": [{
                "code": "STATE_001", "boundaryType": "STATE", "hierarchyType": "ADMIN",
            }],
        }],
    }


# ---------------------------------------------------------------------------
# BR-CM-001: IDGen auto-generates code when omitted
# ---------------------------------------------------------------------------

class TestBR_CM_001_idgen_auto_generates_code_when_omitted:
    """Created employee without explicit code gets a code from IDGen."""

    def test_employee_without_code_gets_generated_code(
        self, request, base_url, auth_headers
    ):
        resp = _post(request.node, f"{base_url}/employees", auth_headers,
                     {"employee": [_base_employee()]})
        assert resp.status_code in (200, 201), f"Create failed: {resp.text}"
        emp = (resp.json().get("employees") or [resp.json()])[0]
        assert emp.get("code"), "code must be auto-generated by IDGen when omitted"


# ---------------------------------------------------------------------------
# BR-CM-002: Individual service validates individual ID
# ---------------------------------------------------------------------------

class TestBR_CM_002_individual_service_validates_individual_id:
    """When INDIVIDUAL_ENABLED, a nonexistent individualId is rejected."""

    @pytest.fixture(autouse=True)
    def _skip_without_individual_url(self, request):
        if not request.config.getoption("--individual-url", default=None):
            pytest.skip("--individual-url not provided; cross-module test skipped")

    def test_nonexistent_individual_id_rejected(self, request, base_url, auth_headers):
        emp = {**_base_employee(), "individualId": f"NONEXISTENT-{uuid.uuid4().hex[:8]}"}
        resp = _post(request.node, f"{base_url}/employees", auth_headers,
                     {"employee": [emp]})
        assert resp.status_code == 400, \
            f"Expected 400 for nonexistent individualId, got {resp.status_code}: {resp.text}"


