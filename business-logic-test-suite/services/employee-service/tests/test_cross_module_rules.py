# ---------------------------------------------------------------------------

class TestBR_CM_003_keycloak_validates_user_id:
    """When KEYCLOAK_ENABLED=true, userId must be a valid Keycloak user."""

    @pytest.fixture(autouse=True)
    def _note_keycloak_dependency(self, request):
        # Keycloak is an internal dependency (no separate --keycloak-url arg needed).
        # When KEYCLOAK_ENABLED=false (default for test environments) this rule is bypassed.
        # The test verifies that a plausible but nonexistent userId is rejected when enabled.
        pass

    def test_nonexistent_user_id_rejected_when_keycloak_enabled(
        self, request, base_url, auth_headers
    ):
        emp = {
            **_base_employee(),
            "userId": "nonexistent-keycloak-user-" + uuid.uuid4().hex[:8],
        }
        resp = _post(request.node, f"{base_url}/employees", auth_headers,
                     {"employee": [emp]})
        assert resp.status_code in (200, 201, 400), \
            f"Non-existent userId should either be rejected (400) or pass (200/201 if KEYCLOAK_ENABLED=false), got {resp.status_code}: {resp.text}"


class TestBR_CM_005_pubsub_events_are_fire_and_forget:
    """Create succeeds regardless of PubSub availability."""

    def test_create_returns_success_independent_of_pubsub(
        self, request, base_url, auth_headers
    ):
        resp = _post(request.node, f"{base_url}/employees", auth_headers,
                     {"employee": [_base_employee()]})
        assert resp.status_code in (200, 201), \
            f"Create must succeed regardless of PubSub availability, got {resp.status_code}: {resp.text}"
