"""
Cross-module rule tests for Registry service.
"""
import pytest
import requests as req_lib
from tests.helpers.curl_builder import attach_curl


def _post(node, url, headers, body):
    r = req_lib.Request("POST", url, headers=headers, json=body)
    p = r.prepare()
    attach_curl(node, p)
    return req_lib.Session().send(p)


_VALID_DEFINITION = {
    "$schema": "https://json-schema.org/draft/2020-12/schema",
    "type": "object",
    "properties": {"name": {"type": "string"}},
    "required": ["name"],
}


# ---------------------------------------------------------------------------
# BR-CM-001: IDGen library generates all registryIds on create
# ---------------------------------------------------------------------------

class TestBR_CM_001_idgen_library_generates_registry_ids:
    """Created data record has a non-empty registryId."""

    def test_created_data_has_registry_id(self, request, base_url, auth_headers):
        resp = _post(request.node, f"{base_url}/schema/seed-schema/data", auth_headers,
                     {"data": {"name": "IDGen Test Entry"}})
        assert resp.status_code in (200, 201), f"Data create failed: {resp.text}"
        record = resp.json()
        assert record.get("registryId") or record.get("id"), \
            "registryId must be generated by IDGen library and present in response"


